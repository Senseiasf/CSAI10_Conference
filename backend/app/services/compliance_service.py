    @classmethod
    def get_compliance_info(cls, dest_id: str, profile: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
        """
        Возвращает детальную сводку визовых правил, требований к паспорту и необходимых документов.
        """
        dest_key = dest_id.lower().strip() if dest_id else "sochi"
        info = cls.COMPLIANCE_DATABASE.get(dest_key)

        if not info:
            # Fallback для неопознанного направления
            return {
                "country": "Международное направление",
                "is_domestic": False,
                "passport_required": "Загранпаспорт гражданина РФ",
                "passport_validity": "Не менее 6 месяцев от даты выезда",
                "visa_policy": "Требуется уточнение визового режима",
                "stay_limit": "Зависит от визы",
                "required_docs": ["Загранпаспорт", "Медстраховка", "Обратный билет"],
                "special_notes": "Рекомендуем сверить правила въезда на официальном сайте консульства страны назначения.",
                "badge": "🛂 Проверка документов",
                "summary": "🛂 **Правила въезда:** Требуется загранпаспорт со сроком действия не менее 6 месяцев и медицинская страховка."
            }

        profile = profile or {}
        has_kids = profile.get("has_kids", False)
        
        # Составляем текстовое резюме для ответа агента
        summary_lines = [
            f"🛂 **Правила въезда и документы ({info['country']}):**",
            f"• 📄 **Документ:** {info['passport_required']} ({info['passport_validity']}).",
            f"• 🎟️ **Визовый режим:** {info['visa_policy']} (лимит: {info['stay_limit']})."
        ]
        
        if has_kids:
            if info["is_domestic"]:
                summary_lines.append("• 👶 **Для детей до 14 лет:** Свидетельство о рождении с обязательной отметкой/вкладышем о гражданстве РФ.")
            else:
                summary_lines.append("• 👶 **Для детей:** Обязателен собственный отдельный загранпаспорт (дети, вписанные в паспорт родителей, не допускаются).")

        summary_lines.append(f"• ℹ️ **Особые условия:** {info['special_notes']}")

        result = dict(info)
        result["summary"] = "\n".join(summary_lines)
        return result
